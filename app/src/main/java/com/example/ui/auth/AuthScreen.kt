                                        errorMessage = msg
                                    },
                                    scope = scope,
                                    onAuthCancelled = {
                                        isSigningIn = false
                                        errorMessage = "Sign-in was cancelled. Tap below to continue with your Google account."
                                    }
                                )
                            },
                            enabled = !isSigningIn && !isCheckingAutoSignIn,
                            shape = RoundedCornerShape(14.dp),
                            colors = ButtonDefaults.buttonColors(
                                containerColor = MaterialTheme.colorScheme.primary
                            ),
                            modifier = Modifier
                                .fillMaxWidth()
                                .height(54.dp)
                                .testTag("google_sign_in_button")
                        ) {
                            if (isSigningIn || isCheckingAutoSignIn) {
                                CircularProgressIndicator(
                                    modifier = Modifier.size(22.dp),
                                    color = MaterialTheme.colorScheme.onPrimary,
                                    strokeWidth = 2.4.dp
                                )
                                Spacer(Modifier.width(10.dp))
                                Text(
                                    if (isCheckingAutoSignIn) "Checking session..." else "Signing in...",
                                    style = MaterialTheme.typography.labelLarge
                                )
                            } else {
                                Icon(Icons.Rounded.Login, contentDescription = null)
                                Spacer(Modifier.width(10.dp))
                                Text(
                                    "Sign in / Register with Google",
                                    style = MaterialTheme.typography.titleSmall
                                )
                            }
                        }

                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.Center,
                            modifier = Modifier.fillMaxWidth()
                        ) {
                            Icon(
                                Icons.Rounded.VerifiedUser,
                                contentDescription = null,
                                tint = MaterialTheme.colorScheme.secondary,
                                modifier = Modifier.size(16.dp)
                            )
